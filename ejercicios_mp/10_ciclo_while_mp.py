horas_capacitacion = 0
while horas_capacitacion < 40:
    print("El empleado está en capacitación,", horas_capacitacion, "horas acumuladas")
    horas_capacitacion += 10

print("El empleado completó su capacitación")

dias_vacaciones = 15
while dias_vacaciones > 0:
    print("Al empleado le quedan", dias_vacaciones, "días de vacaciones")
    dias_vacaciones -= 5
print("El empleado se quedó sin días de vacaciones")